document.addEventListener('DOMContentLoaded', () => {
    // 1. Access the jsPDF library
    const { jsPDF } = window.jspdf;

    // 2. Select all elements with the 'btn-download' class
    const buttons = document.querySelectorAll('.btn-download');

    // 3. Loop through each button to add click logic
    buttons.forEach(btn => {
        btn.addEventListener('click', () => {

            // Get data from HTML attributes
            const filename = btn.getAttribute('data-filename');
            const title = btn.getAttribute('data-title');
            const bodyContent = btn.getAttribute('data-body');

            // Create new PDF Document
            const doc = new jsPDF();

            // --- HEADER ---
            doc.setFont("helvetica", "bold");
            doc.setFontSize(18);
            doc.setTextColor(40, 40, 100); // Navy Blue
            doc.text(title, 20, 20);

            // Draw a line under the title
            doc.setLineWidth(0.5);
            doc.line(20, 25, 190, 25);

            // --- BODY ---
            doc.setFont("helvetica", "normal");
            doc.setFontSize(12);
            doc.setTextColor(0, 0, 0); // Black

            // Automatically wrap text if it's too long for one line
            const splitText = doc.splitTextToSize(bodyContent, 170);
            doc.text(splitText, 20, 40);

            // --- FOOTER ---
            doc.setFontSize(10);
            doc.setTextColor(150, 150, 150); // Grey
            doc.text("Generated by MyFantasia School System", 20, 280);

            // --- SAVE ---
            doc.save(filename);
        });
    });
});